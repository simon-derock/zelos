"""Zelos evaluation entry point: regenerates every published number.

Runs E1/E2/E9 (scripts/eval_vision.py), E4 (scripts/eval_retrieval.py), E5 (scripts/eval_grounding.py),
then aggregates them into results/results.json + results/results.md (tables and findings computed from
the JSON — nothing typed by hand).

  python evaluate.py                     # everything (needs data/raw from `make data`)
  python evaluate.py --skip-vision       # reuse results/e1,e2,e9.json (reviewer smoke run, < 2 min)
  python evaluate.py --check-provenance  # fail if a number in README.md is absent from results.json
Offline by default: Cohere and Workers AI responses are replayed from committed caches.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
RES = ROOT / "results"
sys.path.insert(0, str(ROOT / "src"))

from zelos.common.config import provenance, write_json  # noqa: E402


def run(script: str, *args: str) -> None:
    print(f"\n=== {script} {' '.join(args)}", flush=True)
    env = {**os.environ, "PYTHONPATH": str(ROOT / "src")}
    subprocess.run([sys.executable, str(ROOT / script), *args], check=True, cwd=ROOT, env=env)


def load(name: str) -> dict:
    p = RES / f"{name}.json"
    return json.loads(p.read_text()) if p.exists() else {}


def pct(x: float | None) -> str:
    return "n/a" if x is None else f"{100 * x:.1f}%"


def f3(x: float | None) -> str:
    return "n/a" if x is None else f"{x:.3f}"


def findings(e1: dict, e2: dict, e4: dict, e5: dict) -> list[str]:
    out = []
    if e1:
        o, b = e1["overall"], e1.get("batch_reference", {})
        out.append(f"E1: on {e1['n_images']} real OoC images x {len(e1['kinds'])} corruptions x 5 severities, Zelos flags "
                   f"{pct(o['detection_rate_sev3plus'])} of severity>=3 corruptions and names the injected cause for "
                   f"{pct(o['attribution_acc_detected'])} of flagged images (top-2: {pct(o['attribution_top2_detected'])}; "
                   f"chance {pct(o['attribution_random_baseline'])}).")
        if b:
            out.append(f"E1: the pre-registered dev-session reference also flags {pct(e1['clean_flag_rate'])} of clean test "
                       f"images (cross-session acquisition shift). A batch-relative reference (unsupervised, added after "
                       f"that result) lowers clean flags to {pct(b['clean_flag_rate'])} with AUROC "
                       f"{f3(b['auroc_clean_vs_sev3plus'])} vs {f3(o['auroc_clean_vs_sev3plus'])}.")
    if e2:
        d = e2["detectors"]
        best = max(d, key=lambda k: d[k]["auroc"])
        out.append(f"E2: the expert good/bad label measures culture quality, not image artifacts: the artifact QC score "
                   f"reaches AUROC {f3(d['zelos_qc_score']['auroc'])} while non-parametric kNN label transfer on the same "
                   f"physics features reaches {f3(d['knn_handcrafted_k15']['auroc'])} (best detector: {best}, "
                   f"n_test={e2['n_test']}, session-grouped split).")
    if e4 and "modes" in e4:
        m = e4["modes"]
        bestm = max(m, key=lambda k: m[k]["paper_level"].get("mrr", 0))
        out.append(f"E4: over {e4['corpus']['n_papers']} open-access papers / {e4['corpus']['n_chunks']} chunks, the best "
                   f"retrieval mode is {bestm} with paper-level MRR {f3(m[bestm]['paper_level'].get('mrr'))}.")
    if e5:
        out.append("E5: see results/e5.md for template vs ungated LLM vs gated LLM grounding rates.")
    return out


def md(e1: dict, e2: dict, e4: dict, e5: dict, e9: dict, prov: dict) -> str:
    L = ["# Zelos results", "", f"Generated by `python evaluate.py` at commit `{prov['git_sha'][:7]}` "
         f"({prov['timestamp_utc']}). Every number below is read from results/*.json.", ""]
    if e1:
        L += ["## E1 — controlled corruptions on real OoC images (ground truth by construction)", "",
              f"n = {e1['n_images']} test images, {len(e1['kinds'])} corruption kinds x 5 severities; reference = "
              f"{e1['n_reference_images']} clean dev-session images.", "",
              "| Reference | Detection (sev>=3) | Clean flag rate | AUROC clean vs sev>=3 | Attribution acc. | Top-2 | Focus-only AUROC |",
              "|---|---:|---:|---:|---:|---:|---:|"]
        o = e1["overall"]
        L.append(f"| pre-registered (dev sessions) | {pct(o['detection_rate_sev3plus'])} | {pct(e1['clean_flag_rate'])} | "
                 f"{f3(o['auroc_clean_vs_sev3plus'])} | {pct(o['attribution_acc_detected'])} | {pct(o['attribution_top2_detected'])} | {f3(o['auroc_focus_only'])} |")
        if "batch_reference" in e1:
            b = e1["batch_reference"]
            L.append(f"| batch-relative (post hoc) | {pct(b['detection_rate_sev3plus'])} | {pct(b['clean_flag_rate'])} | "
                     f"{f3(b['auroc_clean_vs_sev3plus'])} | {pct(b['attribution_acc_detected'])} | {pct(b['attribution_top2_detected'])} | {f3(b['auroc_focus_only'])} |")
        L += ["", f"Chance attribution = {pct(e1['overall']['attribution_random_baseline'])}.", "",
              "| Corruption | Expected cause | AUROC | Attribution (pre-reg) | Attribution (batch) |", "|---|---|---:|---:|---:|"]
        for k, v in e1["per_kind"].items():
            vb = e1.get("per_kind_batch", {}).get(k, {})
            L.append(f"| {k} | {v['expected_label']} | {f3(v['auroc_clean_vs_sev3plus'])} | "
                     f"{pct(v['attribution_acc_detected'])} | {pct(vb.get('attribution_acc_detected'))} |")
        L.append("")
    if e2:
        L += ["## E2 — agreement with the dataset's expert good/bad decision", "",
              f"Session-grouped split: n_dev = {e2['n_dev']}, n_test = {e2['n_test']} ({e2['n_test_bad']} bad).", "",
              "| Detector | AUROC | 95% CI |", "|---|---:|---|"]
        for k, v in e2["detectors"].items():
            L.append(f"| {k} | {f3(v['auroc'])} | {f3(v['auroc_ci95'][0])}–{f3(v['auroc_ci95'][1])} |")
        r = e2["zelos_at_review_threshold"]
        L += ["", f"QC flag at z>{r['threshold_z']}: balanced accuracy {f3(r['balanced_accuracy'])}, "
              f"Cohen's kappa {f3(r['cohen_kappa'])} (majority baseline balanced accuracy {f3(r['majority_baseline_balanced_accuracy'])}).", ""]
    for name in ("e4", "e5"):
        p = RES / f"{name}.md"
        if p.exists():
            L += [p.read_text().strip(), ""]
    if e9:
        L += ["## E9 — efficiency (CPU)", "", f"Metric suite p50 {e9['metrics_ms_p50']:.0f} ms, p95 {e9['metrics_ms_p95']:.0f} ms "
              f"per {e9['image_shape']} image (n = {e9['n']}); full inspect p50 {e9['inspect_ms_p50']:.0f} ms.", ""]
    return "\n".join(L) + "\n"


def numbers_in(text: str) -> set[str]:
    return set(re.findall(r"(?<![\w.])\d+\.\d+%?|(?<![\w.])\d{2,}%", text))


def check_provenance() -> int:
    """T27: every decimal / percentage in README.md must appear in results/results.md (built from JSON)."""
    readme = (ROOT / "README.md").read_text() if (ROOT / "README.md").exists() else ""
    allowed = numbers_in((RES / "results.md").read_text()) | numbers_in(json.dumps(load("results")))
    # numbers that are not results (versions, dataset facts) are whitelisted explicitly in README via <!--np-->
    readme = re.sub(r"<!--np-->.*?<!--/np-->", "", readme, flags=re.S)
    missing = sorted(n for n in numbers_in(readme) if n not in allowed)
    if missing:
        print("PROVENANCE FAIL — numbers in README not found in results:", missing)
        return 1
    print("PROVENANCE PASS")
    return 0


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--skip-vision", action="store_true")
    ap.add_argument("--skip-retrieval", action="store_true")
    ap.add_argument("--skip-grounding", action="store_true")
    ap.add_argument("--check-provenance", action="store_true")
    a = ap.parse_args()
    os.environ.setdefault("ZELOS_LLM_MODE", "replay")
    if not a.skip_vision:
        run("scripts/eval_vision.py")
    if not a.skip_retrieval and (ROOT / "scripts/eval_retrieval.py").exists():
        run("scripts/eval_retrieval.py")
    if not a.skip_grounding and (ROOT / "scripts/eval_grounding.py").exists():
        run("scripts/eval_grounding.py")
    e1, e2, e4, e5, e9 = (load(n) for n in ("e1", "e2", "e4", "e5", "e9"))
    prov = provenance()
    fx = findings(e1, e2, e4, e5)
    write_json(RES / "results.json", {"e1": e1, "e2": e2, "e4": e4, "e5": e5, "e9": e9, "findings": fx, "provenance": prov})
    (RES / "results.md").write_text(md(e1, e2, e4, e5, e9, prov) + "\n## Findings\n\n" + "\n".join(f"- {f}" for f in fx) + "\n")
    print("\n".join(fx))
    if a.check_provenance:
        sys.exit(check_provenance())


if __name__ == "__main__":
    main()
